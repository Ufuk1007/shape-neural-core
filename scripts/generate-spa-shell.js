import { readFileSync, unlinkSync, writeFileSync } from 'fs';

const html = readFileSync('dist/index.html', 'utf-8');
const output = `// Auto-generated by scripts/generate-spa-shell.js — do not edit manually\nexport const SPA_SHELL = ${JSON.stringify(html)};\n`;
writeFileSync('api/_spa-shell.ts', output);
unlinkSync('dist/index.html');
console.log('✓ api/_spa-shell.ts generated; static root removed so the SEO route handles /');
